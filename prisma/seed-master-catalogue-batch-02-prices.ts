function normalize(value: string) {
  return value
    .trim()
    .toUpperCase()
    .replace(/&/g, " AND ")
    .replace(/[^A-Z0-9]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function priceLookupKey(row: (typeof PRICE_ROWS)[number]) {
  return [
    "BATCH02",
    normalize(row.supplier),
    row.productNormalizedName,
    row.finish ? normalize(row.finish) : "NO FINISH",
    normalize(row.base),
    String(row.size),
    row.uom,
    row.effectiveOn,
  ].join("|");
}

async function main() {
  let basesCreated = 0;
  let pricesCreated = 0;
  let pricesUpdated = 0;

  for (const row of PRICE_ROWS) {
    const supplier = await prisma.supplier.findFirst({
      where: {
        OR: [
          { name: { equals: row.supplier, mode: "insensitive" } },
          {
            normalizedName: {
              equals: normalize(row.supplier),
              mode: "insensitive",
            },
          },
        ],
      },
      select: { id: true },
    });

    if (!supplier) throw new Error(`Supplier not found: ${row.supplier}`);

    const product = await prisma.masterCatalogueProduct.findUnique({
      where: {
        supplierId_normalizedName: {
          supplierId: supplier.id,
          normalizedName: row.productNormalizedName,
        },
      },
      select: { id: true },
    });

    if (!product) {
      throw new Error(
        `Batch 01 product not found: ${row.supplier} / ${row.productName}`,
      );
    }

    let finishId: string | null = null;
    if (row.finish) {
      const finish = await prisma.masterProductFinish.findUnique({
        where: {
          productId_normalizedName: {
            productId: product.id,
            normalizedName: normalize(row.finish),
          },
        },
        select: { id: true },
      });

      if (!finish) {
        throw new Error(
          `Finish not found: ${row.productName} / ${row.finish}. Run Batch 01 first.`,
        );
      }
      finishId = finish.id;
    }

    const normalizedBase = normalize(row.base);
    const existingBase = await prisma.masterProductBase.findUnique({
      where: {
        productId_normalizedName: {
          productId: product.id,
          normalizedName: normalizedBase,
        },
      },
      select: { id: true },
    });

    const base = await prisma.masterProductBase.upsert({
      where: {
        productId_normalizedName: {
          productId: product.id,
          normalizedName: normalizedBase,
        },
      },
      create: {
        productId: product.id,
        name: row.base,
        normalizedName: normalizedBase,
      },
      update: { name: row.base },
      select: { id: true },
    });

    if (!existingBase) basesCreated += 1;

    const lookupKey = priceLookupKey(row);
    const existingPrice = await prisma.masterProductPrice.findUnique({
      where: { lookupKey },
      select: { id: true },
    });

    await prisma.masterProductPrice.upsert({
      where: { lookupKey },
      create: {
        lookupKey,
        productId: product.id,
        finishId,
        baseId: base.id,
        unitSize: row.size,
        uom: row.uom,
        price: row.price,
        currency: "ZAR",
        effectiveFrom: new Date(`${row.effectiveOn}T00:00:00.000Z`),
        sourceFile: row.sourceFile,
        sourceRow: row.sourceRow,
        note: row.note,
        isActive: true,
      },
      update: {
        finishId,
        baseId: base.id,
        price: row.price,
        sourceFile: row.sourceFile,
        sourceRow: row.sourceRow,
        note: row.note,
        isActive: true,
      },
    });

    if (existingPrice) pricesUpdated += 1;
    else pricesCreated += 1;
  }

  console.log(
    `Batch 02 complete: ${PRICE_ROWS.length} confirmed prices processed, ` +
      `${basesCreated} bases created, ${pricesCreated} prices created, ` +
      `${pricesUpdated} prices updated.`,
  );
}

main()
  .catch((error) => {
    console.error("Batch 02 master catalogue price seed failed:", error);
    process.exitCode = 1;
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
