function displaySite(site: (typeof sites)[number]) {
  return `${site.code} - ${site.name}`;
}

async function findSupervisorByEmail(email: string) {
  return prisma.supervisor.findFirst({
    where: {
      user: {
        email: {
          equals: email,
          mode: "insensitive",
        },
      },
    },
    select: {
      id: true,
      user: {
        select: {
          name: true,
          email: true,
        },
      },
    },
  });
}

async function assignSupervisorToSite(supervisorId: string, siteId: string) {
  // Uses any so the seed still compiles if your generated Prisma type is behind.
  const db = prisma as any;

  if (!db.supervisorSiteAssignment) {
    console.warn(
      "supervisorSiteAssignment model not found on Prisma Client. Site was seeded but supervisor assignment was skipped.",
    );
    return false;
  }

  const existing = await db.supervisorSiteAssignment.findFirst({
    where: {
      supervisorId,
      siteId,
      endsOn: null,
    },
    select: { id: true },
  });

  if (existing) return true;

  await db.supervisorSiteAssignment.create({
    data: {
      supervisorId,
      siteId,
      startsOn: new Date("2026-07-01T00:00:00.000Z"),
    },
  });

  return true;
}

async function main() {
  let seeded = 0;
  let assigned = 0;
  let missingSupervisors = 0;
  const missingSupervisorEmails = new Set<string>();

  for (const site of sites) {
    const savedSite = await prisma.site.upsert({
      where: { code: site.code },
      update: {
        name: site.name,
        client: site.client,
        specStatus: site.specStatus as any,
        jobStatus: "NOT_STARTED",
        isActive: true,
      },
      create: {
        code: site.code,
        name: site.name,
        client: site.client,
        specStatus: site.specStatus as any,
        jobStatus: "NOT_STARTED",
        isActive: true,
      },
      select: {
        id: true,
        code: true,
        name: true,
      },
    });

    seeded += 1;

    const supervisor = await findSupervisorByEmail(site.supervisorEmail);

    if (!supervisor) {
      missingSupervisors += 1;
      missingSupervisorEmails.add(site.supervisorEmail);
      console.warn(
        `Seeded ${displaySite(site)} but missing supervisor ${site.supervisorLabel} <${site.supervisorEmail}>`,
      );
      continue;
    }

    const ok = await assignSupervisorToSite(supervisor.id, savedSite.id);
    if (ok) assigned += 1;

    console.log(
      `Seeded ${savedSite.code} - ${savedSite.name} | ${site.client} | ${supervisor.user.name ?? supervisor.user.email} | ${site.specStatus}`,
    );
  }

  console.log("\nDone.");
  console.log(`Seeded/updated sites: ${seeded}`);
  console.log(`Supervisor assignments confirmed/created: ${assigned}`);
  console.log(`Missing supervisor references: ${missingSupervisors}`);

  if (missingSupervisorEmails.size > 0) {
    console.log("\nMissing supervisors:");
    for (const email of missingSupervisorEmails) {
      console.log(`- ${email}`);
    }
  }
}

main()
  .catch((error) => {
    console.error(error);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
